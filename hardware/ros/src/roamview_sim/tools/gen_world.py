#!/usr/bin/env python3
"""Generate worlds/roamview_test.sdf: two rooms (8 x 6 m) joined by a 0.9 m doorway, a table (the LiDAR sees
only its legs), a cabinet, a bin, a 70 mm box below the LiDAR plane (the bumper finds it), a 12 mm threshold strip
and a 0.6 m stairwell drop at x 2.4-3.4, y -3.0 to -1.8 for cliff tests.

    python3 tools/gen_world.py
"""
from pathlib import Path


def box(name, x, y, z, sx, sy, sz, rgb, collide=True):
    r, g, b = rgb
    col = (f'\n        <collision name="collision"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>'
           '</collision>') if collide else ""
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {z} 0 0 0</pose>
      <link name="link">{col}
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse><specular>0.1 0.1 0.1 1</specular></material>
        </visual>
      </link>
    </model>"""


def cyl(name, x, y, z, rad, h, rgb):
    r, g, b = rgb
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {z} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><cylinder><radius>{rad}</radius><length>{h}</length></cylinder></geometry></collision>
        <visual name="visual">
          <geometry><cylinder><radius>{rad}</radius><length>{h}</length></cylinder></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse><specular>0.1 0.1 0.1 1</specular></material>
        </visual>
      </link>
    </model>"""


FLOOR, WALL, WOOD, GREY = (0.78, 0.76, 0.72), (0.92, 0.92, 0.90), (0.55, 0.38, 0.22), (0.45, 0.47, 0.50)
PIT, YELLOW, BLUE = (0.25, 0.26, 0.28), (0.95, 0.75, 0.10), (0.20, 0.35, 0.70)
m = []
# floor slabs (top at z = 0) around the stairwell opening x 2.4..3.4, y -3.0..-1.8
m.append(box("floor_main", -0.8, 0.0, -0.05, 6.4, 6.0, 0.1, FLOOR))
m.append(box("floor_east", 3.2, 0.6, -0.05, 1.6, 4.8, 0.1, FLOOR))
m.append(box("floor_corner", 3.7, -2.4, -0.05, 0.6, 1.2, 0.1, FLOOR))
# stairwell: bottom 0.6 m down, lined on all four sides
m.append(box("stairwell_bottom", 2.9, -2.4, -0.65, 1.0, 1.2, 0.1, PIT))
m.append(box("stairwell_wall_w", 2.39, -2.4, -0.3, 0.02, 1.2, 0.6, PIT))
m.append(box("stairwell_wall_e", 3.41, -2.4, -0.3, 0.02, 1.2, 0.6, PIT))
m.append(box("stairwell_wall_n", 2.9, -1.79, -0.3, 1.0, 0.02, 0.6, PIT))
m.append(box("stairwell_wall_s", 2.9, -3.01, -0.3, 1.0, 0.02, 0.6, PIT))
m.append(box("stairwell_edge_paint", 2.9, -1.765, 0.0005, 1.0, 0.03, 0.001, YELLOW, collide=False))
# outer walls 0.8 m high, inner wall at x = 1.0 with a 0.9 m doorway (y 0.5 to 1.4)
m.append(box("wall_north", 0.0, 3.05, 0.4, 8.2, 0.1, 0.8, WALL))
m.append(box("wall_south", 0.0, -3.05, 0.4, 8.2, 0.1, 0.8, WALL))
m.append(box("wall_west", -4.05, 0.0, 0.4, 0.1, 6.0, 0.8, WALL))
m.append(box("wall_east", 4.05, 0.0, 0.4, 0.1, 6.0, 0.8, WALL))
m.append(box("wall_inner_s", 1.0, -1.25, 0.4, 0.1, 3.5, 0.8, WALL))
m.append(box("wall_inner_n", 1.0, 2.2, 0.4, 0.1, 1.6, 0.8, WALL))
# table: top 0.75 m up, the LiDAR (286 mm) only sees the legs
tx, ty = -2.6, 1.8
m.append(box("table_top", tx, ty, 0.735, 1.2, 0.8, 0.03, WOOD))
for i, (dx, dy) in enumerate([(-0.55, -0.35), (-0.55, 0.35), (0.55, -0.35), (0.55, 0.35)]):
    m.append(box(f"table_leg_{i}", tx + dx, ty + dy, 0.36, 0.05, 0.05, 0.72, WOOD))
m.append(box("cabinet", -1.0, -2.45, 0.45, 0.6, 0.5, 0.9, GREY))
m.append(cyl("bin", 2.2, 1.9, 0.3, 0.18, 0.6, BLUE))
m.append(box("low_box", -2.0, -1.0, 0.035, 0.30, 0.20, 0.07, (0.80, 0.25, 0.20)))
m.append(box("threshold_strip", -3.0, -1.8, 0.006, 0.06, 1.2, 0.012, (0.35, 0.30, 0.25)))

world = f"""<?xml version="1.0"?>
<!-- GENERATED by tools/gen_world.py. RoamView test ground: two rooms (8 x 6 m), a 0.9 m doorway, a table, a cabinet,
     a bin, a 70 mm box below the LiDAR plane, a 12 mm threshold strip and a 0.6 m stairwell drop
     (x 2.4-3.4, y -3.0 to -1.8). -->
<sdf version="1.9">
  <world name="roamview_test">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>

    <gravity>0 0 -9.81</gravity>
    <scene>
      <ambient>0.55 0.55 0.55 1</ambient>
      <background>0.75 0.78 0.82 1</background>
      <shadows>true</shadows>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.85 0.85 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>
{''.join(m)}
  </world>
</sdf>
"""
dst = Path(__file__).resolve().parent.parent / "worlds" / "roamview_test.sdf"
dst.write_text(world)
print(f"wrote {dst}")
